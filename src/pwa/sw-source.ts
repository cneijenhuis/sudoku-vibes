/**
 * Source text of the generated service worker (`dist/sw.js`). Kept here, as a pure function of
 * the file list and cache name, so it can be unit-tested by running it against fake `caches`.
 *
 * Strategy:
 * - install: precache every built file into one versioned cache (bypassing the HTTP cache, so a
 *   stale copy is never frozen in), all or nothing. There is deliberately no `skipWaiting`: a
 *   page already open keeps being served by the worker (and cache) it started with, so old and
 *   new files are never mixed; the new worker takes over once the old pages are closed.
 * - activate: delete this app's other caches, claim open pages.
 * - navigations: network first, revalidated (a new deploy shows up on the next online visit), falling back to
 *   the cached page when offline, on a server error or when the network is too slow.
 * - everything else (same origin GET): cache first from the versioned cache, else the network.
 *   Misses are not stored, so the cache only ever holds one build.
 */

export const CACHE_PREFIX = 'sudoku-vibes-';

export interface SwOptions {
  /** Full cache name, `CACHE_PREFIX` plus a version hash. */
  cacheName: string;
  /** Built files, as paths relative to the site root (e.g. `assets/app-1a2b.js`), excluding sw.js. */
  files: readonly string[];
}

/** URL of a built file relative to `sw.js`, which sits at the site root. */
export const relativeUrl = (path: string): string => `./${path}`;

export function buildServiceWorker({ cacheName, files }: SwOptions): string {
  const urls = ['./', ...files.map(relativeUrl)];
  return `// Generated by the sudoku-vibes build. Do not edit.
'use strict';

const CACHE = ${JSON.stringify(cacheName)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const FILES = ${JSON.stringify(urls, null, 2)};
const NAV_TIMEOUT_MS = 3000;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES.map((url) => new Request(url, { cache: 'reload' })))),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

function withTimeout(promise, ms) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('network timeout')), ms);
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error);
      },
    );
  });
}

async function navigate(request) {
  try {
    // 'no-cache' revalidates with the server even inside the HTTP cache lifetime (GitHub Pages
    // sends max-age=600), so a new deploy is seen on the next online visit, not ten minutes later.
    const response = await withTimeout(fetch(request, { cache: 'no-cache' }), NAV_TIMEOUT_MS);
    if (response.status < 500) return response;
    throw new Error('server error');
  } catch (error) {
    const cache = await caches.open(CACHE);
    const cached = await cache.match('./index.html');
    if (cached) return cached;
    throw error;
  }
}

async function asset(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request, { ignoreSearch: true });
  return cached || fetch(request);
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(request.mode === 'navigate' ? navigate(request) : asset(request));
});
`;
}
